import { Modul } from '../types';

export function getQuranDefaultPage(surahNo: number, ayatNo: number = 1): number {
  if (!surahNo || surahNo <= 0 || surahNo > 114) return 1;
  const bounds = QURAN_SURAH_PAGE_BOUNDS[surahNo];
  if (!bounds) return QURAN_SURAH_START_PAGES[surahNo] || 1;
  const [startPage, endPage] = bounds;
  if (startPage === endPage) {
    return startPage;
  }
  const totalAyats = QURAN_SURAH_TOTAL_AYATS[surahNo] || 1;
  const pageSpan = endPage - startPage;
  const ratio = Math.max(0, Math.min(1, (ayatNo - 1) / (totalAyats > 1 ? (totalAyats - 1) : 1)));
  const calculatedPage = startPage + Math.round(ratio * pageSpan);
  return Math.min(Math.max(calculatedPage, startPage), endPage);
}

export function getQuranPageNumber(surahNo: number, ayatNo: number, modul?: Modul): number {
  if (modul && modul.isiAyat) {
    const foundAyat = modul.isiAyat.find(a => a.nomorAyat === ayatNo);
    if (foundAyat && foundAyat.halaman !== undefined && foundAyat.halaman !== null) {
      return foundAyat.halaman;
    }
  }
  return getQuranDefaultPage(surahNo, ayatNo);
}

export function getQuranPageRangeString(surahNo: number, ayatAwal: number, ayatAkhir: number, modul?: Modul): string {
  if (!surahNo || surahNo <= 0) return '';
  const pageAwal = getQuranPageNumber(surahNo, ayatAwal, modul);
  const pageAkhir = getQuranPageNumber(surahNo, ayatAkhir, modul);
  if (pageAwal === pageAkhir) {
    return `Halaman ${pageAwal}`;
  }
  return `Halaman ${pageAwal} - ${pageAkhir}`;
}
